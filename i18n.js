let currentLang = 'en';

function applyLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;

  // Update canonical URL
  const canonical = document.querySelector('link[rel="canonical"]');
  if (canonical) {
    canonical.href = lang === 'en' 
      ? 'https://agency.munister.com.ua/' 
      : `https://agency.munister.com.ua/?lang=${lang}`;
  }

  const t = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = t[key] !== undefined ? t[key] : translations.en[key];
    if (value !== undefined) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = value;
      } else if (el.tagName === 'OPTION') {
        el.textContent = value;
      } else {
        el.innerHTML = value;
      }
    }
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  localStorage.setItem('lang', lang);

  // Update URL params without reloading
  const url = new URL(window.location);
  if (lang === 'en') {
    url.searchParams.delete('lang');
  } else {
    url.searchParams.set('lang', lang);
  }
  window.history.replaceState({}, '', url);

  // Sections rendered in JS (the coverage map) redraw their own strings.
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}

document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => applyLang(btn.dataset.lang));
});

const urlLang = new URLSearchParams(window.location.search).get('lang');
const requested = ['uk', 'en', 'de', 'pl', 'es', 'pt', 'it'].includes(urlLang) ? urlLang : null;
// English is the public default. A translated URL is intentionally explicit:
// it is shareable, predictable for international visitors and never silently
// changes because a browser or a previous session happened to use another locale.
applyLang(requested || 'en');

